export function avatarSprite(id: string): Sprite {
  const avatar = AVATARS.find((a) => a.id === id) ?? AVATARS[0];
  return {
    rows: AVATAR_ROWS,
    palette: {
      h: avatar.hair,
      s: avatar.skin,
      c: avatar.shirt,
      k: NAVY,
      m: "#b4232f",
    },
  };
}
