/**
 * Market-sizing templates for on-demand Product Case estimations. Every
 * template is a chain of factors: one base (the unit that buys), the factors
 * that narrow or multiply it, a trap that looks like the base and is not, and
 * noise. `generate.ts` turns a template into a full estimation spec.
 */
import type { Company, IndustryKey } from "@/core/case-engine";

import type { NumberRange } from "../generator";

export type FactRole = "base" | "factor" | "trap" | "noise";

export interface TemplateFact {
  id: string;
  role: FactRole;
  label: string;
  /** How the fact reads inside the formula: "households", "with a dog". */
  short: string;
  unit: string;
  source: string;
  range: NumberRange;
  note: string;
}

export interface EstimationTemplate {
  key: string;
  industry: IndustryKey;
  company: Company;
  title: string;
  prompt: string;
  answerUnit: string;
  constants: { value: number; label: string }[];
  facts: TemplateFact[];
  /** First sentences of the model answer: why this base and not the trap. */
  reasoning: string;
  principle: string;
}

